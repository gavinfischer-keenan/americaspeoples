import assert from 'node:assert/strict';
import {mapSetting} from '../scripts/browser-fixture.mjs';
import {chromium} from 'playwright';
import {createStaticServer} from '../scripts/static-server.mjs';
const server=createStaticServer('dist');await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({executablePath:process.env.BROWSER_PATH||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960}});page.setDefaultTimeout(15000);
const base=`http://127.0.0.1:${server.address().port}`;
try{
 await page.goto(base+'/#review/northeast-kruger2-context');
 await page.locator('[data-action="locate"]').click();await page.locator('#selected-records h4').waitFor();
 const details=page.locator('#selected-records');
 assert.match(await details.locator('.reader-finding').innerText(),/stone.*point|point.*stone/i);
 assert.doesNotMatch(await details.locator('.reader-finding').innerText(),/audit|preserved from|typological coexistence/i);
 const where=details.locator('dt').filter({hasText:/^Where$/}).locator('+ dd');
 assert.match(await where.innerText(),/Brompton|Sherbrooke/);
 assert.doesNotMatch(await where.innerText(),/anchor|precision|schematic|excavation coordinate/i);
 assert.equal(await details.locator('.reader-methods').getAttribute('open'),null,'technical detail starts collapsed');
 assert.match(await details.locator('.reader-date-meaning').innerText(),/broad|approximate/i);
 await page.screenshot({path:'test-results/reader-kruger-desktop.png'});
 await details.getByText('Evidence and uncertainty',{exact:true}).click();
 assert.ok(await details.locator('.reader-methods p').first().isVisible());
 await page.setViewportSize({width:1024,height:768});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await details.getByText('Evidence and uncertainty',{exact:true}).click();
 await page.screenshot({path:'test-results/reader-kruger-tablet.png'});
 await details.getByRole('link',{name:/Full review/}).click();
 assert.match(await page.locator('.review-page').innerText(),/What this shows/);
 await page.goto(base+'/#review/d18-language-mani-1562');
 const history=page.locator('.review-history');
 assert.match(await history.innerText(),/Franciscan friar Diego de Landa/);
 assert.match(await history.innerText(),/548|ceramic/);
 assert.match(await history.innerText(),/public ceremony/);
 assert.equal(await page.locator('.review-technical').getAttribute('open'),null);
 await page.screenshot({path:'test-results/reader-mani-tablet.png',fullPage:true});
 await page.goto(base+'/#atlas/pacific');
 if(await page.getByRole('button',{name:'Pause',exact:true}).isVisible())await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.setViewportSize({width:1440,height:960});
 await mapSetting(page,()=>page.locator('#whole-movie').click());
 await page.locator('#americas-jump').selectOption('1000');
 const hawaii=page.locator('#map-host [data-overlay][aria-label*="Hawaiʻi: alternative Bayesian colonization estimates"]');
 const feature=await hawaii.boundingBox();assert.ok(feature);
 await page.mouse.move(feature.x+feature.width/2,feature.y+feature.height/2);
 const tooltip=page.getByRole('tooltip');await tooltip.waitFor();
 const box=await tooltip.boundingBox();
 assert.ok(box.x+box.width<=feature.x||box.x>=feature.x+feature.width||box.y+box.height<=feature.y||box.y>=feature.y+feature.height,'Hawaiʻi stays uncovered by its tooltip');
 assert.ok((await tooltip.innerText()).length<750,'hover text remains compact');
 await page.screenshot({path:'test-results/hawaii-tooltip-clear.png'});
 console.log('PASS readable Kruger2 and Maní histories, named places, expandable evidence, tablet and Hawaiʻi hover clearance.');
}finally{await browser.close();await new Promise(r=>server.close(r));}
